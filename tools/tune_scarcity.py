#!/usr/bin/env python3
"""Tune how much of each ore forms, so every element's average in the outer
500 m of the bodies sits near its natural level (Earth's crust, times TARGET).

Reads the plain generator's measurements (no specialties):
data/reference/materials-plain.csv, written by
    cargo run --release --bin abundance -- --plain
and rewrites the [geology.scarcity] table at the end of data/geology.toml.
Each ore's scarcity is the share of the places it could form where it does;
the rest are gangue or host rock. An ore is scaled by its most over-abundant
element (so none overshoots), and only elements that ores carry are tuned:
natural compositions (meteoritic iron, cores, ices) are left as they are.
Run it, re-measure, run it again: two or three rounds settle it.
"""
import csv, collections, math, pathlib, re, tomllib, glob

root = pathlib.Path(__file__).resolve().parent.parent
LOW, HIGH = 0.5, 3.0          # the band, in times Earth's crust
FLOOR, CEIL = 1e-5, 30.0
RADIOGENIC = {"Ra", "Po", "Rn", "Tc", "At", "Fr"}   # left to radioactivity
# Volatiles whole worlds are made of (sulfur, carbon, ice worlds): not ore-limited.
SKIP = RADIOGENIC | {"C", "S", "N", "H", "Cl"}

crust = tomllib.load(open(root / "data/reference/crust-ppm.toml", "rb"))
mats = {}
for f in ["materials.toml", "materials-catalogue.toml", "geology.toml", "glamour.toml", "burning.toml", "life.toml"]:
    path = root / "data" / f
    if path.exists():
        for m in tomllib.load(open(path, "rb")).get("material", []):
            mats[m["name"]] = m.get("composition", {})
geo = tomllib.load(open(root / "data/geology.toml", "rb"))["geology"]

# The ores: everything the geology rules or the bodies scatter as deposits.
tunable = set()
for k in ["hydrothermal", "cumulate", "skarn", "accessory"]:
    for r in geo.get(k, []):
        tunable.add(r["material"])
if geo.get("cumulate_nugget"):
    tunable.add(geo["cumulate_nugget"])
for f in glob.glob(str(root / "data/bodies/*.toml")):
    b = tomllib.load(open(f, "rb"))
    for s in b.get("sprinkle", []):
        tunable.add(s["material"])
    for l in (b.get("strata") or {}).get("lens", []):
        if l.get("nugget"):
            tunable.add(l["nugget"])
# Rock-forming skarn minerals stay as they are (iron ore, garnet).
tunable -= {geo.get("vein_gangue"), "magnetite", "garnet"}
# Placed by hand in a body file (blobs, veins, strata...): scarcity can't
# change those, so they don't count as what ores add on that body.
by_hand = set()
for f in glob.glob(str(root / "data/bodies/*.toml")):
    name = pathlib.Path(f).stem
    text = open(f).read()
    for block in re.split(r"\n(?=\[)", text):
        if block.startswith("[[sprinkle]]"):
            continue
        for m in re.findall(r'material = "([^"]+)"', block):
            by_hand.add((name, m))
scar = dict(geo.get("scarcity", {}))

rows = list(csv.DictReader(open(root / "data/reference/materials-plain.csv")))
bodies = sorted({r["body"] for r in rows})
ore_ppm = collections.defaultdict(float)
for r in rows:
    m = r["material"]
    if m.startswith("molten "):
        m = m[len("molten "):]
    if m in tunable and (r["body"], m) not in by_hand:
        for e, f in mats.get(m, {}).items():
            ore_ppm[e] += float(r["skin_ppm"]) * f / len(bodies)

changes = []
for m in sorted(tunable):
    comp = mats.get(m, {})
    lo, hi = 0.0, math.inf
    for e, f in comp.items():
        if f < 0.01 or e in SKIP or crust.get(e, 1e9) > 2000:
            continue
        have = ore_ppm.get(e, 0.0)
        if have <= 0:
            continue
        lo = max(lo, LOW * crust[e] / have)
        hi = min(hi, HIGH * crust[e] / have)
    if hi == math.inf:
        continue
    factor = min(max(1.0, lo), hi)          # in the band if it can be; never over
    factor = min(10.0, max(0.1, factor)) ** 0.8   # damped: the measurements are noisy
    old = scar.get(m, 1.0)
    new = float(f"{min(CEIL, max(FLOOR, old * factor)):.3g}")
    if abs(new - old) / old > 0.05:
        changes.append((m, old, new))
    scar[m] = new

for m, o, n in changes:
    print(f"{m:22} {o:10.4g} -> {n:.4g}")
lines = ["# ---- scarcity: generated by tools/tune_scarcity.py (re-run it after changes) ----",
         "# The share of the places each ore could form where it does; the rest is",
         "# gangue or host rock; over 1, it is picked that much more often. Tuned so",
         "# ores bring each element to %g-%g x Earth's crust on average over the" % (LOW, HIGH),
         "# bodies. Specialties raise it on their bodies.",
         "[geology.scarcity]"]
for m in sorted(scar):
    if scar[m] != 1.0:
        lines.append(f'"{m}" = {scar[m]}')
path = root / "data/geology.toml"
text = path.read_text()
cut = text.find("# ---- scarcity: generated")
if cut >= 0:
    text = text[:cut].rstrip() + "\n"
path.write_text(text + "\n" + "\n".join(lines) + "\n")
